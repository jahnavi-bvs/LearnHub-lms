// Builds seed/modules.sql from the Markdown files in seed/course-content/.
//   node backend/seed/build-modules-sql.mjs
//
// Each file holds one course:   # course: <exact title>
// and its modules in order:     ## module: <title>   then   video: <11-char id>   (or "video:" if none)
// Everything else in a module is its Markdown lesson notes.
// The build stops on missing notes sections or malformed video ids.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const contentDir = join(here, 'course-content');
const REQUIRED_SECTIONS = ['Introduction', 'Key concepts', 'Definitions', 'Example', 'Key takeaways'];

function parseCourse(file) {
  const text = readFileSync(join(contentDir, file), 'utf8').replace(/\r\n/g, '\n');
  const courseTitle = text.match(/^# course: (.+)$/m)?.[1]?.trim();
  if (!courseTitle) throw new Error(`${file}: missing "# course:" line`);

  const modules = text.split(/^## module: /m).slice(1).map((chunk, index) => {
    const newline = chunk.indexOf('\n');
    const title = chunk.slice(0, newline).trim();
    const rest = chunk.slice(newline + 1);
    const video = rest.match(/^video:[ \t]*(\S*)[ \t]*$/m);
    if (!video) throw new Error(`${file}: "${title}" has no video: line`);
    const videoId = video[1] || null;
    if (videoId && !/^[A-Za-z0-9_-]{11}$/.test(videoId)) throw new Error(`${file}: "${title}" has a bad video id`);
    const notes = rest.replace(video[0], '').trim();
    for (const section of REQUIRED_SECTIONS) {
      if (!notes.includes(`### ${section}`)) throw new Error(`${file}: "${title}" is missing ${section}`);
    }
    return { position: index + 1, title, videoId, notes };
  });
  return { courseTitle, modules };
}

/** Doubles quotes and escapes backslashes, so any text is safe inside a SQL string. */
const sql = (value) => (value === null ? 'NULL' : `'${value.replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);

const courses = readdirSync(contentDir).filter((f) => f.endsWith('.md')).sort().map(parseCourse);

// Notes must be different for every module, and a video must not repeat within a course
const seenNotes = new Set();
for (const { courseTitle, modules } of courses) {
  const videos = new Set();
  for (const m of modules) {
    if (seenNotes.has(m.notes)) throw new Error(`Duplicate notes: ${m.title}`);
    seenNotes.add(m.notes);
    if (m.videoId && videos.has(m.videoId)) throw new Error(`${courseTitle}: video repeated at ${m.title}`);
    videos.add(m.videoId);
  }
}

const statements = courses.flatMap(({ courseTitle, modules }) => modules.map((m) => `INSERT INTO learnhub_course.course_modules
    (course_id, position, title, youtube_video_id, notes, created_at, updated_at)
SELECT c.id, ${m.position}, ${sql(m.title)}, ${sql(m.videoId)}, ${sql(m.notes)}, UTC_TIMESTAMP(6), UTC_TIMESTAMP(6)
FROM learnhub_course.courses c
WHERE c.title = ${sql(courseTitle)}
  AND NOT EXISTS (SELECT 1 FROM learnhub_course.course_modules m WHERE m.course_id = c.id AND m.title = ${sql(m.title)});`));

writeFileSync(join(here, 'modules.sql'), `-- GENERATED by build-modules-sql.mjs from course-content/*.md. Edit those files, not this one.
-- Before running: the courses must exist (courses.sql), and course-service must have started
-- once with the module code so the table exists.
-- Safe to run more than once: a module that already exists is skipped.
--   mysql -u learnhub -p --default-character-set=utf8mb4 < backend/seed/modules.sql

${statements.join('\n\n')}
`);

const total = courses.reduce((sum, c) => sum + c.modules.length, 0);
console.log(`${courses.length} courses, ${total} modules written to seed/modules.sql`);
for (const c of courses) console.log(`  ${String(c.modules.length).padStart(2)}  ${c.courseTitle}`);
