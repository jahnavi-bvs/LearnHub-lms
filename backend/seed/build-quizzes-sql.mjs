// Builds seed/quizzes.sql from seed/quiz-content/*.md.
//   node backend/seed/build-quizzes-sql.mjs
//
// Format:   # course: <exact title>   ## quiz: <title>   ? question   = correct answer   - wrong answer
// The correct answer is written first; options are shuffled here with a fixed formula, so the
// same input always builds the same file. Every course must have quizzes of 5, 6 and 7 questions.

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const contentDir = join(here, 'quiz-content');
const EXPECTED_SIZES = [5, 6, 7];

function parse(text) {
  const courses = [];
  let course = null;
  let quiz = null;
  let question = null;
  for (const raw of text.replace(/\r\n/g, '\n').split('\n')) {
    const line = raw.trim();
    if (line.startsWith('# course: ')) {
      course = { title: line.slice(10).trim(), quizzes: [] };
      courses.push(course);
    } else if (line.startsWith('## quiz: ')) {
      quiz = { title: line.slice(9).trim(), questions: [] };
      course.quizzes.push(quiz);
    } else if (line.startsWith('? ')) {
      question = { text: line.slice(2).trim(), correct: null, wrong: [] };
      quiz.questions.push(question);
    } else if (line.startsWith('= ')) {
      question.correct = line.slice(2).trim();
    } else if (line.startsWith('- ')) {
      question.wrong.push(line.slice(2).trim());
    } else if (line) {
      throw new Error(`Can't read line: ${line}`);
    }
  }
  return courses;
}

/** A repeatable shuffle: sorts options by a hash of the question and option text. */
function shuffle(question) {
  const options = [question.correct, ...question.wrong]
    .map((text) => ({ text, rank: createHash('sha256').update(`${question.text}|${text}`).digest('hex') }))
    .sort((a, b) => a.rank.localeCompare(b.rank))
    .map((o) => o.text);
  return { options, correctIndex: options.indexOf(question.correct) };
}

const sql = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;

const courses = readdirSync(contentDir).filter((f) => f.endsWith('.md')).sort()
  .flatMap((f) => parse(readFileSync(join(contentDir, f), 'utf8')));

const seenQuestions = new Set();
const correctCounts = [0, 0, 0, 0];
let totalQuestions = 0;
const statements = [];

for (const course of courses) {
  const sizes = course.quizzes.map((q) => q.questions.length);
  if (JSON.stringify(sizes) !== JSON.stringify(EXPECTED_SIZES)) {
    throw new Error(`${course.title}: quiz sizes are ${sizes}, expected ${EXPECTED_SIZES}`);
  }
  course.quizzes.forEach((quiz, quizIndex) => {
    // Older timestamps first: quizzes are listed oldest first, so Quiz 1 comes first
    statements.push(`INSERT INTO learnhub_assessment.assessments (course_id, instructor_id, title, created_at)
SELECT c.id, c.instructor_id, ${sql(quiz.title)}, TIMESTAMPADD(SECOND, ${quizIndex - course.quizzes.length}, UTC_TIMESTAMP(6))
FROM learnhub_course.courses c
WHERE c.title = ${sql(course.title)}
  AND NOT EXISTS (SELECT 1 FROM learnhub_assessment.assessments a WHERE a.course_id = c.id AND a.title = ${sql(quiz.title)});
SET @quiz = (SELECT a.id FROM learnhub_assessment.assessments a JOIN learnhub_course.courses c ON a.course_id = c.id
             WHERE c.title = ${sql(course.title)} AND a.title = ${sql(quiz.title)});`);

    quiz.questions.forEach((question, position) => {
      if (question.wrong.length !== 3 || !question.correct) throw new Error(`${quiz.title}: needs 1 correct and 3 wrong: ${question.text}`);
      if (new Set([question.correct, ...question.wrong]).size !== 4) throw new Error(`Duplicate option: ${question.text}`);
      const key = `${course.title}|${question.text}`;
      if (seenQuestions.has(key)) throw new Error(`Repeated question in ${course.title}: ${question.text}`);
      seenQuestions.add(key);

      const { options, correctIndex } = shuffle(question);
      correctCounts[correctIndex]++;
      totalQuestions++;
      statements.push(`INSERT INTO learnhub_assessment.questions (assessment_id, position, text, correct_option_index)
SELECT @quiz, ${position}, ${sql(question.text)}, ${correctIndex} FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM learnhub_assessment.questions q WHERE q.assessment_id = @quiz AND q.position = ${position});
SET @question = (SELECT q.id FROM learnhub_assessment.questions q WHERE q.assessment_id = @quiz AND q.position = ${position});
INSERT IGNORE INTO learnhub_assessment.question_options (question_id, position, option_text) VALUES
${options.map((o, i) => `  (@question, ${i}, ${sql(o)})`).join(',\n')};`);
    });
  });
}

writeFileSync(join(here, 'quizzes.sql'), `-- GENERATED by build-quizzes-sql.mjs from quiz-content/*.md. Edit those files, not this one.
-- Before running: the courses must exist (courses.sql), and assessment-service must have started
-- once so its tables exist. Safe to run more than once: existing rows are skipped.
--   mysql -u learnhub -p --default-character-set=utf8mb4 < backend/seed/quizzes.sql

${statements.join('\n\n')}
`);

const quizCount = courses.reduce((sum, c) => sum + c.quizzes.length, 0);
console.log(`${courses.length} courses, ${quizCount} quizzes, ${totalQuestions} questions written to seed/quizzes.sql`);
console.log(`correct answer position A/B/C/D: ${correctCounts.join(' / ')}`);
